% ==============================================================================
%   c_to_f.m  ·  WEEK 10 CHALLENGE  —  Celsius → Fahrenheit
%   The formula  F = C × 9/5 + 32  — f_to_c's machine, run in reverse.
% ==============================================================================

function f = c_to_f(c)
    f = c * 9 / 5 + 32;
end
