% ==============================================================================
%   f_to_c.m  ·  WEEK 10 CHALLENGE  —  Fahrenheit → Celsius
%   The science-class formula  C = (F − 32) × 5/9,  machined.
% ==============================================================================

function c = f_to_c(f)
    c = (f - 32) * 5 / 9;
end
